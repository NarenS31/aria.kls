#!/usr/bin/env python3.11
"""
Evaluation harness for the ARIA metacognition engine.

Run AFTER metacognition/generate.py has produced the synthetic dataset:

    python3.11 eval/metacognition_eval.py                 # from the aria repo root
    python3.11 metacognition_eval.py                      # from the eval/ dir

Three metrics are computed:

  METRIC 1 — State Detection Accuracy
    Load test.jsonl, run the analyzer on each think-aloud, compare the
    predicted cognitive state to ground truth. Reports accuracy plus
    precision / recall / F1 per state and prints a confusion matrix.

  METRIC 2 — Intervention Appropriateness
    For each state, sample interventions and ask llama3.1:8b to rate each 0-2
    (0 = wrong, 1 = okay, 2 = perfect) for a student in that state. Reports
    the mean appropriateness per state.

  METRIC 3 — State Transition Effectiveness
    Simulate applying an intervention to a synthetic student in a given state
    (the student's reply is generated by an LLM, then re-analysed). Reports the
    rate at which the cognitive state improves, per originating state.

Results are written to data/eval/metacognition_eval_results.json and a summary
table is printed to stdout.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import defaultdict

# Make the sibling `metacognition` package importable whether this script is
# run from the aria repo root (eval/metacognition_eval.py) or from eval/.
HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import ollama  # noqa: E402

from metacognition.analyzer import (  # noqa: E402
    CognitiveStateAnalyzer,
    COGNITIVE_STATES,
    compute_classification_metrics,
    print_confusion_matrix,
    _join_think_aloud,
    _load_jsonl,
)
from metacognition.interventions import (  # noqa: E402
    MetacognitiveInterventionGenerator,
    INTERVENTION_BANK,
    STATE_RANK,
)

DATA_DIR = os.path.join(HERE, "data")
TEST_PATH = os.path.join(DATA_DIR, "synthetic_thinkaloud", "test.jsonl")
RESULTS_DIR = os.path.join(DATA_DIR, "eval")
RESULTS_PATH = os.path.join(RESULTS_DIR, "metacognition_eval_results.json")

JUDGE_MODEL = os.environ.get("ARIA_JUDGE_MODEL", "llama3.1:8b")
SIM_MODEL = os.environ.get("ARIA_META_MODEL", "llama3.2:3b")


# ------------------------------------------------------------------
# JSON helper for LLM output
# ------------------------------------------------------------------

def _parse_json(text: str) -> dict:
    text = (text or "").strip()
    text = re.sub(r"^```(?:json)?", "", text).strip()
    text = re.sub(r"```$", "", text).strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        m = re.search(r"\{.*\}", text, re.DOTALL)
        if not m:
            raise
        return json.loads(m.group(0))


# ------------------------------------------------------------------
# METRIC 1 — State Detection Accuracy
# ------------------------------------------------------------------

def metric_state_detection(test_path: str, use_llm: bool, limit: int = 0) -> dict:
    print("\n" + "=" * 70)
    print("METRIC 1 — State Detection Accuracy")
    print("=" * 70)

    records = _load_jsonl(test_path)
    if limit:
        records = records[:limit]
    analyzer = CognitiveStateAnalyzer(use_llm=use_llm)

    y_true, y_pred = [], []
    for i, rec in enumerate(records, 1):
        text = _join_think_aloud(rec.get("think_aloud", ""))
        y_true.append(rec.get("cognitive_state", ""))
        y_pred.append(analyzer.analyze(text)["state"])
        if i % 20 == 0:
            print(f"  ...{i}/{len(records)}")

    metrics = compute_classification_metrics(y_true, y_pred, COGNITIVE_STATES)
    print_confusion_matrix(metrics["confusion_matrix"], COGNITIVE_STATES)
    print(f"\nAccuracy: {metrics['accuracy']:.1%}  (n={metrics['n']})")
    print(f"\n{'state':12s}{'precision':>11s}{'recall':>9s}{'f1':>8s}{'support':>9s}")
    for state in COGNITIVE_STATES:
        s = metrics["per_state"][state]
        print(f"{state:12s}{s['precision']:>11.3f}{s['recall']:>9.3f}"
              f"{s['f1']:>8.3f}{s['support']:>9d}")

    macro_f1 = sum(metrics["per_state"][s]["f1"] for s in COGNITIVE_STATES) / len(COGNITIVE_STATES)
    metrics["macro_f1"] = round(macro_f1, 3)
    print(f"\nMacro-F1: {macro_f1:.3f}")
    return metrics


# ------------------------------------------------------------------
# METRIC 2 — Intervention Appropriateness
# ------------------------------------------------------------------

def _rate_intervention(state: str, intervention: str) -> int | None:
    prompt = (
        f"Rate this intervention for a student in state {state}:\n"
        f"\"{intervention}\"\n"
        "0=wrong, 1=okay, 2=perfect. JSON only: {\"rating\": 0|1|2}"
    )
    try:
        resp = ollama.chat(
            model=JUDGE_MODEL,
            messages=[
                {"role": "system", "content":
                    "You are an expert learning scientist grading metacognitive "
                    "prompts. A perfect prompt responds to the student's state, "
                    "never gives the answer, and asks one reflective question. "
                    "Respond with JSON only."},
                {"role": "user", "content": prompt},
            ],
            format="json",
            options={"temperature": 0.0, "num_predict": 30},
        )
        data = _parse_json(resp.message.content)
        rating = int(data.get("rating"))
        return max(0, min(2, rating))
    except Exception:
        return None


def metric_intervention_appropriateness(sample_n: int = 10) -> dict:
    print("\n" + "=" * 70)
    print("METRIC 2 — Intervention Appropriateness")
    print(f"(judge = {JUDGE_MODEL}, up to {sample_n} interventions per state)")
    print("=" * 70)

    gen = MetacognitiveInterventionGenerator("eval_judge")
    per_state: dict[str, dict] = {}
    for state in COGNITIVE_STATES:
        bank = INTERVENTION_BANK[state]
        # Sample up to sample_n interventions (cycle the bank if smaller).
        samples = [bank[i % len(bank)] for i in range(min(sample_n, max(sample_n, len(bank))))][:sample_n]
        ratings = []
        for iv in samples:
            r = _rate_intervention(state, iv)
            if r is not None:
                ratings.append(r)
        mean = sum(ratings) / len(ratings) if ratings else None
        per_state[state] = {
            "mean_appropriateness": round(mean, 3) if mean is not None else None,
            "n_rated": len(ratings),
            "ratings": ratings,
        }
        mean_str = f"{mean:.2f}" if mean is not None else "n/a"
        print(f"  {state:12s} mean={mean_str}  (n={len(ratings)})")

    valid = [v["mean_appropriateness"] for v in per_state.values()
             if v["mean_appropriateness"] is not None]
    overall = round(sum(valid) / len(valid), 3) if valid else None
    print(f"\nOverall mean appropriateness: "
          f"{overall if overall is not None else 'n/a'} / 2.0")
    return {"per_state": per_state, "overall_mean": overall, "judge_model": JUDGE_MODEL}


# ------------------------------------------------------------------
# METRIC 3 — State Transition Effectiveness
# ------------------------------------------------------------------

def _simulate_student_reply(state: str, intervention: str) -> str:
    """Ask an LLM to role-play a student's reply to an intervention."""
    prompt = (
        f"You are role-playing a grade-11 student with ADHD who is currently "
        f"feeling {state} on a problem. Your tutor just asked you:\n"
        f"\"{intervention}\"\n\n"
        "Reply in 1-2 sentences as the student would actually think out loud. "
        "It's fine to still struggle, but respond naturally to what was asked. "
        "Output only the student's words."
    )
    try:
        resp = ollama.chat(
            model=SIM_MODEL,
            messages=[
                {"role": "system", "content":
                    "You realistically simulate a struggling student's think-aloud reply."},
                {"role": "user", "content": prompt},
            ],
            options={"temperature": 0.8, "num_predict": 80},
        )
        return resp.message.content.strip()
    except Exception:
        return ""


def metric_transition_effectiveness(trials_per_state: int = 3, use_llm: bool = True) -> dict:
    print("\n" + "=" * 70)
    print("METRIC 3 — State Transition Effectiveness")
    print(f"(simulate = {SIM_MODEL}, {trials_per_state} trials per state)")
    print("=" * 70)

    analyzer = CognitiveStateAnalyzer(use_llm=use_llm)
    gen = MetacognitiveInterventionGenerator("eval_sim")

    # Only the negative states can meaningfully "improve"; positive states are
    # reported too for completeness (improvement = moving to a higher rank).
    per_state: dict[str, dict] = {}
    for state in COGNITIVE_STATES:
        improved = 0
        trials = 0
        transitions = []
        for _ in range(trials_per_state):
            iv = gen.generate(state)
            reply = _simulate_student_reply(state, iv["text"])
            if not reply:
                continue
            new = analyzer.analyze(reply)["state"]
            trials += 1
            did = STATE_RANK.get(new, 0) > STATE_RANK.get(state, 0)
            if did:
                improved += 1
            gen.record_outcome(state, new)
            transitions.append({"intervention": iv["text"], "reply": reply[:120],
                                "new_state": new, "improved": did})
        rate = improved / trials if trials else None
        per_state[state] = {
            "improvement_rate": round(rate, 3) if rate is not None else None,
            "trials": trials,
            "transitions": transitions,
        }
        rate_str = f"{rate:.0%}" if rate is not None else "n/a"
        print(f"  {state:12s} improvement_rate={rate_str}  (trials={trials})")

    neg = ["CONFUSED", "STUCK", "FRUSTRATED", "RUSHING"]
    neg_rates = [per_state[s]["improvement_rate"] for s in neg
                 if per_state[s]["improvement_rate"] is not None]
    overall = round(sum(neg_rates) / len(neg_rates), 3) if neg_rates else None
    print(f"\nMean improvement on negative states: "
          f"{overall if overall is not None else 'n/a'}")
    return {"per_state": per_state, "negative_state_mean_improvement": overall}


# ------------------------------------------------------------------
# Orchestration
# ------------------------------------------------------------------

def print_summary_table(results: dict) -> None:
    print("\n" + "=" * 70)
    print("SUMMARY")
    print("=" * 70)
    m1 = results.get("state_detection", {})
    m2 = results.get("intervention_appropriateness", {})
    m3 = results.get("transition_effectiveness", {})
    print(f"  {'Metric':40s}{'Result':>20s}")
    print(f"  {'-'*40}{'-'*20}")
    if m1:
        acc = m1.get("accuracy")
        print(f"  {'1. State detection accuracy':40s}{acc:>19.1%}")
        print(f"  {'   macro-F1':40s}{m1.get('macro_f1', 0):>20.3f}")
        target = "PASS" if (acc or 0) >= 0.70 else "BELOW 70%"
        print(f"  {'   >70% target':40s}{target:>20s}")
    if m2:
        ov = m2.get("overall_mean")
        print(f"  {'2. Intervention appropriateness /2':40s}"
              f"{(f'{ov:.2f}' if ov is not None else 'n/a'):>20s}")
    if m3:
        ov = m3.get("negative_state_mean_improvement")
        print(f"  {'3. Neg-state improvement rate':40s}"
              f"{(f'{ov:.0%}' if ov is not None else 'n/a'):>20s}")
    print(f"\nResults saved to {RESULTS_PATH}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Evaluate the ARIA metacognition engine.")
    ap.add_argument("--test", default=TEST_PATH, help="Path to test.jsonl")
    ap.add_argument("--no-llm", action="store_true",
                    help="Metric 1: heuristics only (skip analyzer LLM fallback).")
    ap.add_argument("--limit", type=int, default=0, help="Cap test records (metric 1).")
    ap.add_argument("--sample-n", type=int, default=10,
                    help="Interventions sampled per state (metric 2).")
    ap.add_argument("--trials", type=int, default=3,
                    help="Simulation trials per state (metric 3).")
    ap.add_argument("--skip-judge", action="store_true",
                    help="Skip metric 2 (LLM judge).")
    ap.add_argument("--skip-sim", action="store_true",
                    help="Skip metric 3 (LLM simulation).")
    args = ap.parse_args(argv if argv is not None else sys.argv[1:])

    if not os.path.exists(args.test):
        print(f"ERROR: test set not found at {args.test}\n"
              f"Run: python3.11 metacognition/generate.py --samples 50", file=sys.stderr)
        return 1

    results: dict = {}
    results["state_detection"] = metric_state_detection(
        args.test, use_llm=not args.no_llm, limit=args.limit)

    if not args.skip_judge:
        results["intervention_appropriateness"] = metric_intervention_appropriateness(
            sample_n=args.sample_n)
    if not args.skip_sim:
        results["transition_effectiveness"] = metric_transition_effectiveness(
            trials_per_state=args.trials, use_llm=not args.no_llm)

    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(RESULTS_PATH, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, ensure_ascii=False)

    print_summary_table(results)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
