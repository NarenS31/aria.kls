"""'Would you step in?' teacher activity: pure logic (no Gradio), so it can be tested and reused.

Flow per visitor:  consent (Continue / Skip) -> for each moment: step in / stay quiet -> (if step in) kind of help -> reveal ARIA's
decision -> Agree / Disagree -> one CSV row.  No free text anywhere: every value that reaches the CSV comes from a fixed list.
Analysis plan (committed first): docs/teacher_timing_analysis.md.
"""
from __future__ import annotations

import csv
import json
import threading
import time
import uuid
from pathlib import Path
from typing import Optional

MOMENTS_PATH = Path(__file__).resolve().parent.parent / "data" / "teacher_moments.json"
TAPS_PATH = Path(__file__).resolve().parent.parent / "data" / "demo_logs" / "teacher_taps.csv"
N_MOMENTS = 8

COLUMNS = ["session_id", "moment_id", "role", "years_band", "grade_band", "teacher_decision", "teacher_type",
           "aria_decision", "aria_type", "agree", "timestamp"]
DECISIONS = ("step_in", "stay_quiet")
TYPES = ("prompt", "hint", "encouragement", "break", "other")
AGREE = ("agree", "disagree")
PREFER_NOT = "prefer_not_to_say"
ROLES = ("teacher", "aide_or_tutor", "administrator", "parent_or_visitor", "other", PREFER_NOT)
YEARS = ("0-2", "3-5", "6-10", "11-20", "21+", PREFER_NOT)
GRADES = ("elementary_K-5", "middle_6-8", "high_9-12", "college_or_adult", "mixed", PREFER_NOT)
LABELS = {"step_in": "Step in", "stay_quiet": "Stay quiet", "prompt": "A prompt / question", "hint": "A hint", "encouragement": "Encouragement",
          "break": "Suggest a short break", "other": "Something else", "agree": "Agree", "disagree": "Disagree"}
ROLE_LABELS = {"teacher": "Teacher", "aide_or_tutor": "Aide or tutor", "administrator": "Administrator", "parent_or_visitor": "Parent or visitor",
               "other": "Other", PREFER_NOT: "Prefer not to say"}
BAND_LABELS = {PREFER_NOT: "Prefer not to say", "elementary_K-5": "Elementary (K-5)", "middle_6-8": "Middle (6-8)", "high_9-12": "High school (9-12)",
               "college_or_adult": "College or adult", "mixed": "Mixed grades"}
# ARIA's intervention types -> the activity's five answer choices (documented in docs/teacher_timing_analysis.md section 2)
TYPE_MAP = {"hint": "hint", "task_chunking": "prompt", "reflection": "prompt", "encouragement": "encouragement", "break_suggestion": "break"}


def aria_category(intervention_type: str) -> str:
    return TYPE_MAP.get(intervention_type, "other")


def load_moments(path: Path | str = MOMENTS_PATH, expect: Optional[int] = N_MOMENTS) -> list:
    """Moments generated by scripts/make_teacher_moments.py. Raises ValueError on anything malformed."""
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    if expect is not None and len(raw) != expect:
        raise ValueError(f"expected {expect} moments, found {len(raw)}")
    ids = set()
    for m in raw:
        for k in ("id", "problem_prompt", "history", "message", "aria_decision", "aria_type", "aria_reason", "aria_reply", "words_only", "verified_wrong"):
            if k not in m:
                raise ValueError(f"moment {m.get('id')!r} lacks {k!r}")
        if m["aria_decision"] not in DECISIONS:
            raise ValueError(f"moment {m['id']}: bad aria_decision {m['aria_decision']!r}")
        if m["aria_decision"] == "step_in" and m["aria_type"] not in TYPES:
            raise ValueError(f"moment {m['id']}: bad aria_type {m['aria_type']!r}")
        if m["id"] in ids:
            raise ValueError(f"duplicate moment id {m['id']!r}")
        ids.add(m["id"])
    return raw


class TapLog:
    """Append-only CSV, one row per answered moment. Values are validated against the fixed lists, so no free text can be written."""

    def __init__(self, path: Optional[Path | str] = TAPS_PATH):
        self.path = Path(path) if path else None
        self._lock = threading.Lock()
        self.errors = 0

    def write(self, row: dict) -> bool:
        if self.path is None:
            return False
        try:
            self._validate(row)
            with self._lock:
                self.path.parent.mkdir(parents=True, exist_ok=True)
                new = not self.path.exists() or self.path.stat().st_size == 0
                with open(self.path, "a", newline="", encoding="utf-8") as f:
                    w = csv.DictWriter(f, fieldnames=COLUMNS)
                    if new:
                        w.writeheader()
                    w.writerow({c: row.get(c, "") for c in COLUMNS})
            return True
        except Exception:  # noqa: BLE001 - never lose the visitor's screen over a write error
            self.errors += 1
            return False

    @staticmethod
    def _validate(r: dict):
        ok = {"role": ROLES, "years_band": YEARS, "grade_band": GRADES, "teacher_decision": DECISIONS, "aria_decision": DECISIONS, "agree": AGREE}
        for k, allowed in ok.items():
            if r.get(k) not in allowed:
                raise ValueError(f"{k}={r.get(k)!r}")
        if r["teacher_decision"] == "step_in" and r.get("teacher_type") not in TYPES:
            raise ValueError("teacher_type")
        if r["teacher_decision"] == "stay_quiet" and r.get("teacher_type", "") != "":
            raise ValueError("teacher_type must be empty when staying quiet")
        if r["aria_decision"] == "step_in" and r.get("aria_type") not in TYPES:
            raise ValueError("aria_type")
        if r["aria_decision"] == "stay_quiet" and r.get("aria_type", "") != "":
            raise ValueError("aria_type must be empty when ARIA stays quiet")
        sid, mid = str(r.get("session_id", "")), str(r.get("moment_id", ""))
        if not (len(sid) == 12 and sid.isalnum()) or not mid.replace("_", "").replace("-", "").isalnum():
            raise ValueError("session_id/moment_id")


class Activity:
    """State machine for ONE visitor. Phases: consent -> decision -> type -> reveal -> (next moment) ... -> done | skipped."""

    def __init__(self, moments: list, log: TapLog):
        self.moments, self.log = moments, log
        self.session_id = uuid.uuid4().hex[:12]
        self.phase = "consent"
        self.i = 0
        self.profile = {"role": PREFER_NOT, "years_band": PREFER_NOT, "grade_band": PREFER_NOT}
        self._decision: Optional[str] = None
        self._type = ""
        self.rows_written = 0

    @property
    def moment(self) -> Optional[dict]:
        return self.moments[self.i] if self.phase in ("decision", "type", "reveal") and self.i < len(self.moments) else None

    def set_profile(self, role=PREFER_NOT, years=PREFER_NOT, grade=PREFER_NOT):
        self.profile = {"role": role if role in ROLES else PREFER_NOT, "years_band": years if years in YEARS else PREFER_NOT,
                        "grade_band": grade if grade in GRADES else PREFER_NOT}

    def consent(self, accept: bool):
        if self.phase != "consent":
            return
        self.phase = "decision" if accept and self.moments else "skipped"       # Skip records nothing

    def decide(self, decision: str):
        if self.phase != "decision" or decision not in DECISIONS:
            return
        self._decision, self._type = decision, ""
        self.phase = "type" if decision == "step_in" else "reveal"

    def choose_type(self, kind: str):
        if self.phase != "type" or kind not in TYPES:
            return
        self._type = kind
        self.phase = "reveal"

    def reveal(self) -> Optional[dict]:
        """What ARIA decided on the current moment (shown only after the visitor's own answer)."""
        if self.phase != "reveal":
            return None
        m = self.moments[self.i]
        return {"aria_decision": m["aria_decision"], "aria_type": m["aria_type"] if m["aria_decision"] == "step_in" else "",
                "reason": m["aria_reason"], "reply": m["aria_reply"] if m["aria_decision"] == "step_in" else "",
                "teacher_decision": self._decision, "teacher_type": self._type}

    def agree(self, answer: str):
        """Agree / Disagree: writes the row and moves on."""
        if self.phase != "reveal" or answer not in AGREE:
            return
        m = self.moments[self.i]
        ok = self.log.write({
            "session_id": self.session_id, "moment_id": m["id"], **self.profile, "teacher_decision": self._decision, "teacher_type": self._type,
            "aria_decision": m["aria_decision"], "aria_type": m["aria_type"] if m["aria_decision"] == "step_in" else "", "agree": answer,
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S")})
        self.rows_written += bool(ok)
        self._decision, self._type = None, ""
        self.i += 1
        self.phase = "decision" if self.i < len(self.moments) else "done"
