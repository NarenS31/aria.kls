def run_generation(per_state: int, seed: int, workers: int,
                   models: dict) -> list[dict]:
    print("=" * 70)
    print("STEP 1 — Regenerate held-out sets with different generators")
    print("=" * 70)
    statuses = []
    for model, tag in models.items():
        statuses.append(generate_holdout(model, tag, per_state, seed, workers))
    return statuses


def run_eval(models: dict, use_llm: bool, limit: int) -> dict:
    print("\n" + "=" * 70)
    print("STEP 2 — Run the UNCHANGED classifier on each generator")
    print("=" * 70)
    analyzer = CognitiveStateAnalyzer(use_llm=use_llm)

    # Baseline: llama3.1-generated held-out test split.
    if not os.path.exists(TEST_PATH):
        raise FileNotFoundError(
            f"llama test split not found at {TEST_PATH}. Run "
            "metacognition/generate.py first.")
    print(f"\n[{LLAMA_TAG}] baseline (original test split): {TEST_PATH}")
    llama_metrics = classify_file(TEST_PATH, analyzer, limit=limit)
    print_confusion_matrix(llama_metrics["confusion_matrix"], COGNITIVE_STATES)
    _r = llama_metrics["route"]
    print(f"  accuracy={llama_metrics['accuracy']:.3f}  "
          f"macro-F1={llama_metrics['macro_f1']:.3f}  n={llama_metrics['n']}  "
          f"route: heuristic={_r['pct_heuristic']}%  llm={_r['pct_llm']}%")
    llama_acc = llama_metrics["accuracy"]

    per_generator: dict[str, dict] = {}
    # Keep records around for the lexical analysis (Step 4).
    records_by_tag: dict[str, list[dict]] = {}
    records_by_tag[LLAMA_TAG] = _load_jsonl(TEST_PATH)[: (limit or None)]

    for model, tag in models.items():
        path = os.path.join(OUT_DIR, f"holdout_{tag}.jsonl")
        if not os.path.exists(path):
            print(f"\n[{tag}] MISSING {path} — skipping (run generation first).")
            per_generator[tag] = {"status": "missing", "path": path}
            continue
        print(f"\n[{tag}] classifying {path}")
        m = classify_file(path, analyzer, limit=limit)
        print_confusion_matrix(m["confusion_matrix"], COGNITIVE_STATES)
        gap = round((llama_acc - m["accuracy"]) * 100, 2)
        _r = m["route"]
        print(f"  accuracy={m['accuracy']:.3f}  macro-F1={m['macro_f1']:.3f}  "
              f"n={m['n']}  gap={gap:+.2f} pts  "
              f"route: heuristic={_r['pct_heuristic']}%  llm={_r['pct_llm']}%")
        records_by_tag[tag] = _load_jsonl(path)[: (limit or None)]
        # strip the bulky arrays before storing
        arrays = m.pop("_arrays")
        m["generalization_gap_points"] = gap
        m["gap_interpretation"] = gap_interpretation(gap)
        m["model"] = model
        m["_confidence_mean"] = m.get("mean_confidence")
        per_generator[tag] = m

    # ---- Step 3 summary -------------------------------------------------
    gaps = [v["generalization_gap_points"] for v in per_generator.values()
            if isinstance(v, dict) and "generalization_gap_points" in v]
    mean_gap = round(sum(gaps) / len(gaps), 2) if gaps else None

    # ---- Step 4 lexical overlap ----------------------------------------
    print("\n" + "=" * 70)
    print("STEP 4 — Lexical overlap of top-20 discriminative tokens per state")
    print("=" * 70)
    # top tokens per (tag, state)
    top_by_tag = {tag: top_discriminative(recs)
                  for tag, recs in records_by_tag.items()
                  if recs}
    gen_tags = [t for t in models.values() if t in top_by_tag]
    lexical: dict[str, dict] = {}
    for state in COGNITIVE_STATES:
        sets = [set(top_by_tag[t][state]) for t in gen_tags]
        j_gen = round(jaccard(sets), 3) if len(sets) >= 2 else None
        # also overlap including the llama baseline
        sets_all = sets + ([set(top_by_tag[LLAMA_TAG][state])]
                           if LLAMA_TAG in top_by_tag else [])
        j_all = round(jaccard(sets_all), 3) if len(sets_all) >= 2 else None
        lexical[state] = {
            "jaccard_across_generators": j_gen,
            "jaccard_including_llama": j_all,
            "note": overlap_note(j_gen if j_gen is not None else 0.0),
            "top20_by_generator": {t: top_by_tag[t][state] for t in top_by_tag},
        }
        jg = "n/a" if j_gen is None else f"{j_gen:.3f}"
        print(f"  {state:12s} Jaccard(gen)={jg}   {lexical[state]['note']}")

    mean_jaccard = None
    jvals = [v["jaccard_across_generators"] for v in lexical.values()
             if v["jaccard_across_generators"] is not None]
    if jvals:
        mean_jaccard = round(sum(jvals) / len(jvals), 3)

    results = {
        "meta": {
            "baseline_generator": LLAMA_TAG,
            "baseline_path": TEST_PATH,
            "classifier_use_llm": use_llm,
            "classifier_llm_model": analyzer.model,
            "n_per_generator": {t: per_generator[t].get("n")
                                for t in per_generator
                                if isinstance(per_generator[t], dict)
                                and "n" in per_generator[t]},
            "limit": limit,
        },
        "baseline_llama": {
            "accuracy": llama_metrics["accuracy"],
            "macro_f1": llama_metrics["macro_f1"],
            "mean_confidence": llama_metrics["mean_confidence"],
            "n": llama_metrics["n"],
            "route": llama_metrics["route"],
            "per_state": llama_metrics["per_state"],
            "confusion_matrix": llama_metrics["confusion_matrix"],
        },
        "per_generator": {
            t: ({k: v for k, v in m.items() if not k.startswith("_")}
                if isinstance(m, dict) else m)
            for t, m in per_generator.items()
        },
        "generalization_gap": {
            "per_generator_points": {t: per_generator[t]["generalization_gap_points"]
                                     for t in per_generator
                                     if isinstance(per_generator[t], dict)
                                     and "generalization_gap_points" in per_generator[t]},
            "mean_points": mean_gap,
            "interpretation": gap_interpretation(mean_gap) if mean_gap is not None else None,
        },
        "lexical_overlap": {
            "per_state": lexical,
            "mean_jaccard_across_generators": mean_jaccard,
        },
    }
    return results


def print_summary(results: dict, output_path: str = RESULTS_PATH) -> None:
    print("\n" + "=" * 70)
    print("CROSS-GENERATOR VALIDATION — SUMMARY")
    print("=" * 70)
    base = results["baseline_llama"]
    _br = base.get("route", {})
    print(f"\nBaseline (llama3.1 test): accuracy={base['accuracy']:.3f}  "
          f"macro-F1={base['macro_f1']:.3f}  conf={base['mean_confidence']}  "
          f"(heuristic={_br.get('pct_heuristic')}%  llm={_br.get('pct_llm')}%)")
    print(f"\n{'generator':10s}{'acc':>8s}{'macroF1':>9s}{'conf':>8s}"
          f"{'gap(pts)':>10s}{'%heur':>8s}{'%llm':>7s}")
    for tag, m in results["per_generator"].items():
        if not isinstance(m, dict) or "accuracy" not in m:
            print(f"{tag:10s}   (missing / skipped)")
            continue
        _r = m.get("route", {})
        print(f"{tag:10s}{m['accuracy']:>8.3f}{m['macro_f1']:>9.3f}"
              f"{str(m.get('mean_confidence')):>8s}"
              f"{m['generalization_gap_points']:>+10.2f}"
              f"{str(_r.get('pct_heuristic')):>8s}{str(_r.get('pct_llm')):>7s}")
    gg = results["generalization_gap"]
    print(f"\nMean generalization gap: "
          f"{gg['mean_points']} pts" if gg["mean_points"] is not None else
          "\nMean generalization gap: n/a")
    if gg["interpretation"]:
        print(f"  -> {gg['interpretation']}")
    lo = results["lexical_overlap"]
    print(f"\nMean top-20 Jaccard across generators: "
          f"{lo['mean_jaccard_across_generators']}")
    print(f"\nResults saved to {output_path}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--generate-only", action="store_true",
                    help="Only (re)generate holdout sets, then exit.")
    ap.add_argument("--eval-only", action="store_true",
                    help="Skip generation; evaluate whatever holdouts exist.")
    ap.add_argument("--per-state", type=int, default=50,
                    help="Samples per cognitive state per generator (default 50).")
    ap.add_argument("--seed", type=int, default=1234,
                    help="Spec-generation seed (matches generate.py default).")
    ap.add_argument("--workers", type=int, default=4,
                    help="Concurrent generation requests per model.")
    ap.add_argument("--models", type=str,
                    default=",".join(GENERATORS.keys()),
                    help="Comma-separated ollama model ids for the holdout generators.")
    ap.add_argument("--use-llm", action="store_true",
                    help="Consult the Ollama LLM fallback for low-confidence "
                         "cases. Default is heuristic-only — the recommended "
                         "config, which measured a smaller cross-generator gap "
                         "(9.05 pts) than LLM routing (11.14 pts).")
    ap.add_argument("--no-llm", action="store_true",
                    help=argparse.SUPPRESS)  # deprecated: heuristic-only is now default
    ap.add_argument("--limit", type=int, default=0,
                    help="Cap records per set (debug).")
    ap.add_argument("--output", default=RESULTS_PATH)
    args = ap.parse_args(argv if argv is not None else sys.argv[1:])

    # resolve the requested models to {model: tag}
    models: dict[str, str] = {}
    for mid in [m.strip() for m in args.models.split(",") if m.strip()]:
        models[mid] = GENERATORS.get(mid, re.sub(r"[^a-z0-9]+", "", mid.lower()))

    if not args.eval_only:
        run_generation(args.per_state, args.seed, args.workers, models)
        if args.generate_only:
            return 0

    results = run_eval(models, use_llm=args.use_llm, limit=args.limit)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, ensure_ascii=False)
    print_summary(results, args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
