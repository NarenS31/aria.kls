# ==================================================================
# Step 1 — holdout generation
# ==================================================================

def _existing_ids(path: str) -> set[str]:
    ids: set[str] = set()
    if not os.path.exists(path):
        return ids
    for rec in _load_jsonl(path):
        rid = rec.get("id")
        if rid:
            ids.add(rid)
    return ids


def generate_holdout(
    model: str,
    tag: str,
    per_state: int,
    seed: int,
    workers: int,
    verbose: bool = True,
) -> dict:
    """Generate (resumably) a per_state-per-state holdout set with `model`.

    Returns a small status dict. Records are appended to
    data/synthetic_thinkaloud/holdout_<tag>.jsonl as they complete, so an
    interrupted run can be resumed simply by re-invoking.
    """
    out_path = os.path.join(OUT_DIR, f"holdout_{tag}.jsonl")
    os.makedirs(OUT_DIR, exist_ok=True)

    specs = build_specs(per_state, seed=seed)
    done = _existing_ids(out_path)
    todo = [s for s in specs if s.key not in done]

    target = len(specs)
    if verbose:
        print(f"\n[{tag}] model={model}  target={target}  "
              f"already_have={len(done)}  to_generate={len(todo)}")

    if not todo:
        if verbose:
            print(f"[{tag}] complete — {len(done)}/{target} present.")
        return {"model": model, "tag": tag, "path": out_path,
                "target": target, "generated": len(done), "failed": 0}

    failures = 0
    written = 0
    t0 = time.time()
    # Append mode; flush after each record so progress survives a crash.
    fh = open(out_path, "a", encoding="utf-8")
    lock_free_write = fh  # single writer thread below

    def _work(spec):
        try:
            rec = generate_one(spec, model=model)
            # Tag provenance so downstream code always knows which model made it.
            rec["generator_model"] = model
            rec["generator_tag"] = tag
            return spec.key, rec, None
        except Exception as e:  # noqa: BLE001
            return spec.key, None, str(e)

    try:
        with ThreadPoolExecutor(max_workers=workers) as ex:
            futs = {ex.submit(_work, s): s for s in todo}
            for i, fut in enumerate(as_completed(futs), 1):
                key, rec, err = fut.result()
                if rec is not None:
                    lock_free_write.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    lock_free_write.flush()
                    written += 1
                else:
                    failures += 1
                    if verbose:
                        print(f"  [{tag}] FAIL {key}: {err}")
                if verbose and i % 25 == 0:
                    rate = i / max(1e-6, time.time() - t0)
                    print(f"  [{tag}] {i}/{len(todo)}  "
                          f"({rate:.1f}/s, {written} ok, {failures} failed)")
    finally:
        fh.close()

    total_now = len(_existing_ids(out_path))
    if verbose:
        print(f"[{tag}] done — {total_now}/{target} present "
              f"({written} new, {failures} failed this run).")
    return {"model": model, "tag": tag, "path": out_path, "target": target,
            "generated": total_now, "failed": failures}


# ==================================================================
# Step 2 — classification
# ==================================================================

def classify_file(path: str, analyzer: CognitiveStateAnalyzer, limit: int = 0,
                  workers: int = 4) -> dict:
    """Run the classifier over a labelled jsonl file.

    Returns metrics + parallel arrays (y_true, y_pred, confidence, text).
    Classification is parallelised across `workers` threads: only the ambiguous
    minority actually calls the (slow) LLM, and the shared Ollama client is
    thread-safe, so a small pool cuts wall-clock without changing any verdict.
    Results are re-ordered to match the input, so metrics are deterministic.
    """
    records = _load_jsonl(path)
    if limit:
        records = records[:limit]

    texts = [_join_think_aloud(rec.get("think_aloud", "")) for rec in records]
    y_true = [rec.get("cognitive_state", "") for rec in records]
    results: list[dict] = [None] * len(records)  # type: ignore[list-item]

    def _one(i_text):
        i, text = i_text
        return i, analyzer.analyze(text)

    done = 0
    with ThreadPoolExecutor(max_workers=max(1, workers)) as ex:
        for i, res in ex.map(_one, enumerate(texts)):
            results[i] = res
            done += 1
            if done % 50 == 0:
                print(f"    ...classified {done}/{len(records)}")

    y_pred, confs = [], []
    n_heuristic = 0  # predictions decided by the keyword heuristic
    n_llm = 0        # predictions that reached the multi-generator LLM
    for res in results:
        y_pred.append(res["state"])
        confs.append(float(res.get("confidence", 0.0)))
        # method is "heuristic"/"llm" (+ optional "+audio"); route split is on
        # which stage decided the state.
        if str(res.get("method", "")).startswith("llm"):
            n_llm += 1
        else:
            n_heuristic += 1

    metrics = compute_classification_metrics(y_true, y_pred, COGNITIVE_STATES)
    macro_f1 = sum(metrics["per_state"][s]["f1"] for s in COGNITIVE_STATES) / len(COGNITIVE_STATES)
    metrics["macro_f1"] = round(macro_f1, 4)
    metrics["mean_confidence"] = round(sum(confs) / len(confs), 4) if confs else None
    decided = n_heuristic + n_llm
    metrics["route"] = {
        "heuristic": n_heuristic,
        "llm": n_llm,
        "pct_heuristic": round(100.0 * n_heuristic / decided, 1) if decided else None,
        "pct_llm": round(100.0 * n_llm / decided, 1) if decided else None,
    }
    metrics["_arrays"] = {"y_true": y_true, "y_pred": y_pred,
                          "confidence": confs, "text": texts}
    return metrics


# ==================================================================
# Step 4 — lexical overlap (Monroe et al. 2008 weighted log-odds)
# ==================================================================

_TOKEN_RE = re.compile(r"[a-z0-9']+")


def tokenize(text: str) -> list[str]:
    return [t for t in _TOKEN_RE.findall((text or "").lower()) if len(t) >= 2]


def _state_word_counts(records: list[dict]) -> dict[str, Counter]:
    """Word counts per ground-truth state for one generator's records."""
    per_state: dict[str, Counter] = {s: Counter() for s in COGNITIVE_STATES}
    for rec in records:
        state = rec.get("cognitive_state", "")
        if state not in per_state:
            continue
        per_state[state].update(tokenize(_join_think_aloud(rec.get("think_aloud", ""))))
    return per_state


def weighted_log_odds(counts_i: Counter, counts_rest: Counter,
                      alpha: float = 0.5) -> dict[str, float]:
    """Monroe/Colaresi/Quinn (2008) weighted log-odds-ratio with a symmetric
    Dirichlet prior. Returns a z-score per token: how over-represented the token
    is in group i vs the rest, normalised by its sampling variance. Ubiquitous
    function words score near zero and never top the list.
    """
    vocab = set(counts_i) | set(counts_rest)
    n_i = sum(counts_i.values())
    n_rest = sum(counts_rest.values())
    a0 = alpha * len(vocab)
    z: dict[str, float] = {}
    for w in vocab:
        y_i = counts_i.get(w, 0)
        y_r = counts_rest.get(w, 0)
        # log-odds within each group, prior-smoothed
        num_i = y_i + alpha
        den_i = n_i + a0 - y_i - alpha
        num_r = y_r + alpha
        den_r = n_rest + a0 - y_r - alpha
        if den_i <= 0 or den_r <= 0:
            continue
        delta = math.log(num_i / den_i) - math.log(num_r / den_r)
        var = 1.0 / num_i + 1.0 / num_r
        z[w] = delta / math.sqrt(var)
    return z


def top_discriminative(records: list[dict], top_n: int = 20) -> dict[str, list[str]]:
    """Top-N over-represented tokens per state for one generator's records."""
    per_state = _state_word_counts(records)
    total = Counter()
    for c in per_state.values():
        total.update(c)
    out: dict[str, list[str]] = {}
    for state in COGNITIVE_STATES:
        counts_i = per_state[state]
        counts_rest = total.copy()
        counts_rest.subtract(counts_i)  # rest = all - this state
        # drop negative/zero residuals introduced by subtract
        counts_rest = Counter({w: c for w, c in counts_rest.items() if c > 0})
        z = weighted_log_odds(counts_i, counts_rest)
        ranked = sorted(z.items(), key=lambda kv: kv[1], reverse=True)
        out[state] = [w for w, _ in ranked[:top_n]]
    return out


def jaccard(sets: list[set]) -> float:
    """Mean pairwise Jaccard across a list of sets (1.0 if all identical)."""
    pairs = []
    for a in range(len(sets)):
        for b in range(a + 1, len(sets)):
            u = sets[a] | sets[b]
            inter = sets[a] & sets[b]
            pairs.append(len(inter) / len(u) if u else 1.0)
    return sum(pairs) / len(pairs) if pairs else 1.0


# ==================================================================
# Interpretation bands
# ==================================================================

def gap_interpretation(gap_points: float) -> str:
    if gap_points < 5:
        return ("gap < 5 pts: classifier learned real cognitive signals; it "
                "generalizes across generators.")
    if gap_points <= 15:
        return ("gap 5-15 pts: partial generator overfitting; some signal is "
                "genuine, some is generator-specific.")
    return ("gap > 15 pts: classifier is largely detecting llama3.1's stylistic "
            "fingerprint, NOT cognitive state. Major limitation.")


def overlap_note(j: float) -> str:
    if j >= 0.4:
        return "high overlap: markers are shared/semantic across generators"
    if j >= 0.2:
        return "moderate overlap: partly shared, partly generator-specific"
    return "low overlap: this state's markers are generator-specific, not semantic"


