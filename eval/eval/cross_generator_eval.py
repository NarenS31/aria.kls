#!/usr/bin/env python3.11
"""
Cross-generator validation for the ARIA cognitive-state classifier.

THE PROBLEM this experiment addresses
-------------------------------------
The synthetic think-aloud corpus (data/synthetic_thinkaloud/dataset.jsonl) was
generated by a single model, llama3.1:8b. The heuristic + LLM classifier was
built and tuned against that corpus. A headline accuracy of ~82% on the
llama-generated test split may therefore reflect the classifier learning
*llama3.1's stylistic fingerprint* rather than genuine, model-independent
cognitive-state signals.

To break that circularity we regenerate a fresh, held-out set of think-alouds
with three DIFFERENT open models, run the UNCHANGED classifier on each, and
measure how much accuracy drops. A small drop means the classifier keys on real
cognitive signals; a large drop means it keys on one generator's idiosyncrasies.

What this script does
---------------------
Step 1  Regenerate 50 samples/state (350 total) with each of mistral:7b,
        gemma2:9b and phi3:medium, using the EXACT generation prompts from
        metacognition/generate.py. Written incrementally and resumably to
        data/synthetic_thinkaloud/holdout_<gen>.jsonl.

Step 2  Run the unchanged classifier on each holdout set and on the original
        llama test split. Report accuracy, macro-F1, per-state F1 and a
        confusion matrix per generator.

Step 3  Generalization gap:  gap = acc(llama test) - acc(other generator).
        Reported per generator plus the mean gap, with an interpretation band.

Step 4  Lexical-overlap analysis. For each state, compute the top-20
        discriminative tokens (Monroe et al. 2008 weighted log-odds vs all
        other states) separately per generator, then report the Jaccard overlap
        of those top-20 sets across generators. Low overlap on a state = that
        state's detection rests on generator-specific words, not shared
        semantics.

Everything is written to data/eval/cross_generator_results.json and a summary
is printed.

    python3.11 eval/cross_generator_eval.py                 # generate + eval
    python3.11 eval/cross_generator_eval.py --eval-only     # eval existing holdouts
    python3.11 eval/cross_generator_eval.py --generate-only # only (re)generate
"""

