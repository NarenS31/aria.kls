#!/usr/bin/env python3.11
"""
RQ2 pairing pipeline — scaffolded vs answer-giving tutoring stimuli.

Builds the paired materials RQ2 needs: for each of 10 problems, one simulated
student attempt and two tutor responses to it, one from each condition.

    python3.11 eval/rq2_pipeline.py            # from the aria repo root

  Condition A (scaffolded) is the shipping product path, unchanged:
  ARIAAgent.think_aloud_turn runs observable-move detection, builds the
  task-grounded situation model, and applies the intervention policy. It
  withholds the answer by construction, so nothing here needs to enforce that.

  Condition B (answer-giving) is a separate, deliberately simpler path in this
  file. It reads `answer` and `solution_steps` straight from the question bank
  and states them. It never touches the situation model, the observable-move
  detector, or the JITAI policy — that absence is the manipulation under test.

Display order is randomised ONCE here, under a fixed seed, and written into the
output. Nothing downstream should re-randomise: a form that shuffles at render
time would break the pairing between a rating and the condition it rated.

Reproducibility, precisely: problem selection, persona assignment, and condition
display order are seeded and reproducible. Student attempt text is generated by
the LLM without a fixed seed and will differ between runs. The canonical
stimulus set for this study is frozen in data/rq2_pairs_FROZEN.json and should
not be regenerated.

The two conditions are NOT length- or fluency-matched. A scaffolded reply
acknowledges the attempt and asks one question; an answer-giving reply walks the
keyed steps and states the answer, and is longer. The preview prints the
measured word-count ratio for the set it generated — cite that number rather
than describing the conditions as matched.

Outputs:
  data/rq2_pairs.json         machine-readable pairs (+ hidden unblinding key)
  data/rq2_pairs_preview.md   human review copy, labelled with TRUE conditions

Neither output is the study's stimulus set. Both are overwritten on every run;
the frozen copies alongside them are what the rating form is built from.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import os
import random
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from eval.simulator import SimulatedStudent  # noqa: E402

DATA_DIR = os.path.join(REPO_ROOT, "data")
QUESTION_BANK_PATH = os.path.join(DATA_DIR, "question_bank.json")
PAIRS_PATH = os.path.join(DATA_DIR, "rq2_pairs.json")
PREVIEW_PATH = os.path.join(DATA_DIR, "rq2_pairs_preview.md")

# One seed governs problem selection, persona assignment, and the A/B display
# order — those three are reproducible across runs. It does NOT govern the
# student attempt text: eval/simulator.py samples that at temperature 0.85 with
# no model seed, so the same SEED yields the same problems and personas but
# different attempts, and therefore different scaffolded responses to them.
SEED = 20260818

# Set once, at freeze time, from a validated run. See the module docstring: this
# file — not rq2_pairs.json — is the study's canonical stimulus set.
FROZEN_PAIRS_PATH = os.path.join(DATA_DIR, "rq2_pairs_FROZEN.json")
FROZEN_PREVIEW_PATH = os.path.join(DATA_DIR, "rq2_pairs_FROZEN_preview.md")

SCAFFOLDED = "scaffolded"
ANSWER_GIVING = "answer_giving"

# Target spread. The bank splits science and coding under one `subject`
# ("Science and Coding"), so those two are selected by `topic` instead.
QUOTAS = [
    ("Math", None, 3),
    ("English", None, 3),
    ("Science and Coding", "Science Reasoning", 2),
    ("Science and Coding", "Coding Reasoning", 2),
]

# `scattered` is excluded on purpose. Its topic-jump behaviour produces off-task
# rambling, and RQ2 needs an attempt that shows partial reasoning for both
# conditions to respond to — an off-task turn gives them nothing to work with.
PERSONAS = ["hyperfocus", "frustrated"]

# Placing the student mid-episode rather than at turn 1 is what makes the
# attempt "partway through" instead of an opening question.
SIM_TURN = 2
SIM_MAX_TURNS = 6

# The simulator sometimes returns an off-task follow-up question with no work in
# it. The situation model rightly abstains on those ("not enough task-grounded
# evidence"), which would pair a non-response against a full explanation and
# measure nothing. Such a turn is the blank slate RQ2 explicitly rules out, so
# the attempt is regenerated rather than the policy being loosened.
MAX_ATTEMPT_TRIES = 4


# ------------------------------------------------------------------
# Problem selection
# ------------------------------------------------------------------

def load_question_bank(path: str = QUESTION_BANK_PATH) -> list[dict]:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def select_problems(bank: list[dict], rng: random.Random) -> list[dict]:
    """Pick 10 problems spread across subjects, topics, and task types.

    Every problem in the bank is `difficulty: medium`, so difficulty cannot be
    varied — topic and task_type carry the spread instead. Topics are drawn
    round-robin so a quota never lands twice in the same topic while another
    topic in that subject goes unused.
    """
    selected: list[dict] = []
    for subject, topic, count in QUOTAS:
        pool = [q for q in bank if q.get("subject") == subject
                and (topic is None or q.get("topic") == topic)]
        if len(pool) < count:
            raise ValueError(
                f"question bank has {len(pool)} problems for "
                f"{subject}/{topic or 'any topic'}; need {count}"
            )
        by_topic: dict[str, list[dict]] = {}
        for q in pool:
            by_topic.setdefault(q["topic"], []).append(q)
        topics = sorted(by_topic)
        rng.shuffle(topics)
        for name in topics:
            rng.shuffle(by_topic[name])
        # Round-robin across topics, so 3 Math problems come from 3 topics.
        picked, i = [], 0
        while len(picked) < count:
            name = topics[i % len(topics)]
            if by_topic[name]:
                picked.append(by_topic[name].pop())
            i += 1
        selected.extend(picked)
    return selected


# ------------------------------------------------------------------
# Simulated student attempt (reuses eval/simulator.py)
# ------------------------------------------------------------------

# The model sometimes emits an aside that is not something the student said:
# either prompt bleed echoing a persona parameter — `(uses "I think" probability
# of 0.3)` — or a stage direction like `(trails off)` or `(muttering to self)`.
# All of it would be visible to raters. Matched on this vocabulary rather than
# on any parenthetical, so a real aside ("I got 12 (which felt wrong)") survives.
_ASIDE_VOCAB = (
    r"probability|persona|hedging|frustration|turn\s*number|response\s*length|"
    r"affect|persistence|trail\w*\s*off|pause[sd]?|pausing|sigh\w*|mumbl\w*|"
    r"mutter\w*|grumbl\w*|groan\w*|whisper\w*|shrug\w*|laugh\w*|silence|"
    r"inaudible|to\s+(?:him|her|them|it)self|under\s+\w+\s+breath|quietly"
)
_TRAILING_ASIDE = re.compile(
    rf"\s*\((?=[^)]*\b(?:{_ASIDE_VOCAB})\b)[^)]*\)\s*$", re.IGNORECASE
)
# The same aside mid-utterance, where the simulator has scripted the turn as
# quoted speech: `... is that right?" (muttering to self) "I don't remember`.
# The quote marks on either side belong to the script, not to the student, so
# they come out with it — otherwise they nest inside the coach's own quotation.
_INLINE_ASIDE = re.compile(
    rf"[\"“”]?\s*\((?=[^)]*\b(?:{_ASIDE_VOCAB})\b)[^)]*\)\s*[\"“”]?",
    re.IGNORECASE,
)
# The same aside in roleplay notation: `*sigh*`, `*trails off*`. Gated on the
# vocabulary like the others, so the `*` in a coding answer (`x * x`) survives.
_ASTERISK_ASIDE = re.compile(
    rf"\*(?=[^*]{{0,60}}\b(?:{_ASIDE_VOCAB})\b)[^*]{{0,60}}\*",
    re.IGNORECASE,
)


def _clean_student_text(text: str) -> str:
    """Strip the wrapper artifacts the simulator's LLM sometimes emits."""
    text = (text or "").strip()
    text = re.sub(r"^(student|user)\s*:\s*", "", text, flags=re.IGNORECASE)
    # Before the quote strip, so removing a trailing aside can re-expose a
    # fully quoted utterance underneath it.
    text = _TRAILING_ASIDE.sub("", text).strip()
    text = _INLINE_ASIDE.sub(" ", text)
    text = re.sub(r"\s{2,}", " ", _ASTERISK_ASIDE.sub(" ", text)).strip()
    if len(text) > 1 and text[0] in "\"“" and text[-1] in "\"”":
        text = text[1:-1].strip()
    # A lone opening quote left over from an aside that was not matched would
    # otherwise nest inside the coach's own quotation of the student.
    if text.startswith(('"', "“")) and text.count('"') + text.count("“") == 1:
        text = text[1:].strip()
    # An odd number of quote marks means the scripting was not fully undone;
    # what is left opens a quotation the student never closes.
    if (text.count('"') + text.count("“") + text.count("”")) % 2:
        text = re.sub(r"[\"“”]", "", text).strip()
    return text


def simulate_student_attempt(problem: dict, persona: str, rng: random.Random) -> str:
    """Generate one partway-through attempt at `problem`.

    Reuses SimulatedStudent for the persona parameters and prompt. Two things
    are bound to this problem: the subject label, and the misconception, which
    comes from the problem's own `common_misconceptions` instead of the
    simulator's generic per-subject seed. The conversation history is primed so
    the student is mid-episode and being asked to show work in progress.
    """
    student = SimulatedStudent(persona, "algebra", seed_idx=0)
    student.subject = dataclasses.replace(
        student.subject,
        display=f"{problem['subject']} — {problem['topic']}",
    )
    misconceptions = problem.get("common_misconceptions") or []
    if misconceptions:
        student.misconception = rng.choice(misconceptions)
    student.turn_num = SIM_TURN
    student.max_turns = SIM_MAX_TURNS

    history = [
        {"role": "assistant",
         "content": f"Here is the problem to work on:\n\n{problem['problem']}"},
        {"role": "assistant",
         "content": "Show me the work you have done so far, step by step, "
                    "and say where you are stuck."},
    ]
    return _clean_student_text(student.next_message(history))


# ------------------------------------------------------------------
# Condition A — scaffolded (the existing product path, unchanged)
# ------------------------------------------------------------------

def build_agent():
    """Construct the shipping agent used for Condition A.

    A synthetic profile is used rather than the local student's, so a pipeline
    run neither reads nor writes real student data. `dynamic_problem_coaching`
    stays at its default (off), which is the deterministic policy path.
    """
    from memory.vector_store import VectorStore
    from memory.graph import LearningGraph
    from agent.reasoning import ARIAAgent

    return ARIAAgent(
        vector_store=VectorStore(),
        learning_graph=LearningGraph(),
        user_profile={"name": "RQ2 simulated student", "grade": 11},
        think_aloud_mode=True,
    )


def problem_context(problem: dict) -> dict:
    """Question-bank entry in the shape think_aloud_turn expects."""
    ctx = dict(problem)
    ctx["task_id"] = problem["id"]
    ctx["problem_id"] = problem["id"]
    return ctx


def condition_scaffolded(problem: dict, student_input: str) -> dict:
    """Run the existing intervention pipeline. No changes, no post-processing.

    A fresh agent per call. The pipeline carries session state — coaching
    trace, transfer tracking, intervention history — and RQ2 items have to be
    independent single turns, not turns 1..10 of one long session.
    """
    agent = build_agent()
    agent._current_problem_ctx = problem_context(problem)
    result = agent.think_aloud_turn(student_input)
    return {
        "text": result["question"],
        "situation_label": result["situation_label"],
        "policy_action": result["policy_action"],
        "observable_moves": result.get("observable_moves", []),
        "aria_confidence": result.get("confidence"),
        "intervened": result.get("intervened"),
    }


# ------------------------------------------------------------------
# Condition B — answer-giving (parallel path, not the product pipeline)
# ------------------------------------------------------------------

def _lead_lower(step: str) -> str:
    """Lowercase a step's first letter so it reads after "First, ".

    Left alone when the first word is an acronym or identifier, so SQL keywords
    and code tokens survive: "SELECT identifies..." must not become "sELECT".
    """
    first = step.split(maxsplit=1)[0] if step.split() else ""
    if first and (first.isupper() or any(c.isupper() for c in first[1:])):
        return step
    return step[0].lower() + step[1:]


def condition_answer_giving(problem: dict, student_input: str) -> dict:
    """Explain the answer directly from the question bank.

    The standard-tutoring baseline. It reads the student's attempt only to
    address them, and deliberately does not interpret it: no situation model,
    no observable-move detection, no JITAI policy. Deterministic, so a rerun
    reproduces the stimulus exactly.

    `solution_steps` and `answer` are this bank's names for what the RQ2 spec
    calls expected_steps and correct_answer.
    """
    steps = list(problem.get("solution_steps") or [])
    answer = str(problem.get("answer", "")).strip()
    is_writing = problem.get("task_type") == "writing"

    parts = ["Let me walk you through this one."]
    if steps:
        parts.append(" ".join(
            f"{ordinal}, {_lead_lower(step)}" if step else ""
            for ordinal, step in zip(
                ["First", "Then", "Next", "After that", "Finally"], steps)
        ).strip())
    if answer:
        stop = "" if answer[-1] in ".!?" else "."
        parts.append(
            f"That gets you to what the task is looking for: {answer}{stop}"
            if is_writing else
            f"That gives you the answer: {answer}{stop}"
        )
    ideas = problem.get("key_ideas") or []
    if ideas:
        parts.append(f"The idea doing the work here is {ideas[0]}.")

    return {
        "text": " ".join(p for p in parts if p),
        "source_fields": ["solution_steps", "answer", "key_ideas"],
        "used_situation_model": False,
        "used_jitai": False,
    }


# ------------------------------------------------------------------
# Pair assembly
# ------------------------------------------------------------------

def build_pairs(limit: int = 10, seed: int = SEED) -> list[dict]:
    rng = random.Random(seed)
    random.seed(seed)  # the simulator's persona logic uses the global RNG

    bank = load_question_bank()
    problems = select_problems(bank, rng)[:limit]

    pairs = []
    for i, problem in enumerate(problems, 1):
        persona = PERSONAS[i % len(PERSONAS)]
        print(f"  [{i}/{len(problems)}] {problem['id']} ({persona})",
              end="", flush=True)

        # Keep the strongest attempt seen, so a run that never clears the bar
        # still yields its best stimulus rather than whatever came last.
        best: tuple[str, dict] | None = None
        for attempt in range(1, MAX_ATTEMPT_TRIES + 1):
            student_input = simulate_student_attempt(problem, persona, rng)
            scaffolded = condition_scaffolded(problem, student_input)
            if best is None or (scaffolded["aria_confidence"] or 0) > (
                    best[1]["aria_confidence"] or 0):
                best = (student_input, scaffolded)
            if scaffolded["intervened"]:
                break
            print(f" retry{attempt}", end="", flush=True)

        student_input, scaffolded = best
        weak = not scaffolded["intervened"]
        print(f" {scaffolded['policy_action']}"
              f"{' WEAK-STIMULUS' if weak else ''}", flush=True)
        answer_giving = condition_answer_giving(problem, student_input)

        # Randomised once, here. `display_order` is what the form reads; the
        # hidden block is the unblinding key and must not be shown to raters.
        shown_as_a = rng.choice([SCAFFOLDED, ANSWER_GIVING])
        shown_as_b = ANSWER_GIVING if shown_as_a == SCAFFOLDED else SCAFFOLDED

        pairs.append({
            "problem_id": problem["id"],
            "problem_text": problem["problem"],
            "student_input": student_input,
            "display_order": {"shown_as_A": shown_as_a},
            "response_scaffolded": scaffolded["text"],
            "response_answer_giving": answer_giving["text"],
            "_hidden": {
                "shown_as_A": shown_as_a,
                "shown_as_B": shown_as_b,
                "seed": seed,
                "subject": problem["subject"],
                "topic": problem["topic"],
                "difficulty": problem["difficulty"],
                "task_type": problem["task_type"],
                "persona": persona,
                "attempt_tries": attempt,
                # True means the situation model abstained even on the best
                # attempt: the pair is degenerate and should not go in the form.
                "weak_stimulus": weak,
                "scaffolded_meta": scaffolded,
                "answer_giving_meta": answer_giving,
            },
        })
    return pairs


# ------------------------------------------------------------------
# Output
# ------------------------------------------------------------------

def write_pairs(pairs: list[dict], path: str = PAIRS_PATH) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(pairs, fh, indent=2, ensure_ascii=False)


def response_length_summary(pairs: list[dict]) -> dict:
    """Measured word counts per condition. Reported, not asserted.

    The conditions differ in length by construction, so the honest thing to
    publish is the size of that difference for this set.
    """
    scaffolded = [len(p["response_scaffolded"].split()) for p in pairs]
    answering = [len(p["response_answer_giving"].split()) for p in pairs]
    mean_s = sum(scaffolded) / len(scaffolded)
    mean_a = sum(answering) / len(answering)
    return {
        "scaffolded_mean_words": round(mean_s, 1),
        "answer_giving_mean_words": round(mean_a, 1),
        "ratio": round(mean_a / mean_s, 2),
        "scaffolded_range": [min(scaffolded), max(scaffolded)],
        "answer_giving_range": [min(answering), max(answering)],
    }


def render_preview(pairs: list[dict], seed: int = SEED) -> str:
    length = response_length_summary(pairs)
    lines = [
        "# RQ2 pairs — review copy",
        "",
        "**Not for the rater form.** Every response below is labelled with its "
        "TRUE condition. The form must instead follow `display_order.shown_as_A` "
        f"in `rq2_pairs.json`. Generated with seed `{seed}`; the assignment is "
        "fixed at generation and must not be re-randomised at render time.",
        "",
        f"{len(pairs)} problems.",
        "",
        "**Response length is not matched between conditions.** Measured on "
        f"this set: scaffolded mean **{length['scaffolded_mean_words']} words** "
        f"(range {length['scaffolded_range'][0]}–{length['scaffolded_range'][1]}), "
        f"answer-giving mean **{length['answer_giving_mean_words']} words** "
        f"(range {length['answer_giving_range'][0]}–"
        f"{length['answer_giving_range'][1]}); answer-giving is "
        f"**{length['ratio']}×** the scaffolded length. Length remains a "
        "partial confound and must be reported as this ratio — no write-up "
        "should describe the conditions as fluency- or length-matched.",
        "",
    ]
    weak = [p["problem_id"] for p in pairs if p["_hidden"]["weak_stimulus"]]
    if weak:
        lines += [
            f"⚠️ **{len(weak)} weak stimulus/stimuli**: `{'`, `'.join(weak)}`. "
            "The situation model abstained rather than scaffolding, so the pair "
            "compares a non-response against a full explanation. Replace these "
            "before building the form.",
            "",
        ]
    for i, pair in enumerate(pairs, 1):
        h = pair["_hidden"]
        lines += [
            "---",
            "",
            f"## {i}. `{pair['problem_id']}` — {h['subject']} / {h['topic']}",
            "",
            f"*{h['task_type']} · {h['difficulty']} · persona: {h['persona']} · "
            f"shown as A: **{h['shown_as_A']}***",
            "",
            "**Problem**",
            "",
            f"> {pair['problem_text']}",
            "",
            "**Simulated student attempt**",
            "",
            f"> {pair['student_input']}",
            "",
            f"**TRUE CONDITION: scaffolded** — policy action "
            f"`{h['scaffolded_meta']['policy_action']}`, situation "
            f"\"{h['scaffolded_meta']['situation_label']}\", moves "
            f"{h['scaffolded_meta']['observable_moves'] or 'none'}, "
            f"confidence {h['scaffolded_meta']['aria_confidence']}",
            "",
            f"> {pair['response_scaffolded']}",
            "",
            "**TRUE CONDITION: answer_giving** — direct from "
            "`solution_steps` + `answer`, no situation model, no JITAI",
            "",
            f"> {pair['response_answer_giving']}",
            "",
        ]
    return "\n".join(lines)


def write_preview(pairs: list[dict], path: str = PREVIEW_PATH,
                  seed: int = SEED) -> str:
    text = render_preview(pairs, seed)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return text


def warn_if_frozen_exists(path: str = FROZEN_PAIRS_PATH) -> bool:
    """Say plainly that this run does not touch the study's materials.

    Deliberately non-blocking. Regenerating is still useful — for testing a fix
    before a new study, or for inspecting how the set varies — and the failure
    mode worth preventing is not the run itself but believing afterwards that
    the run replaced what the raters will see.
    """
    if not os.path.exists(path):
        return False
    rel = os.path.relpath(path, REPO_ROOT)
    print(
        f"\nWARNING: A frozen stimulus set already exists at {rel}. "
        "Regenerating will NOT update the frozen file. If you intend to build "
        "a new study, delete or rename the existing frozen file first.\n",
        flush=True,
    )
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--limit", type=int, default=10, help="Problems to pair.")
    ap.add_argument("--seed", type=int, default=SEED,
                    help="Fixes selection, personas, and A/B display order.")
    ap.add_argument("--pairs-output", default=PAIRS_PATH)
    ap.add_argument("--preview-output", default=PREVIEW_PATH)
    ap.add_argument("--no-print", action="store_true",
                    help="Skip echoing the preview to stdout.")
    args = ap.parse_args(argv if argv is not None else sys.argv[1:])

    frozen_exists = warn_if_frozen_exists()

    print(f"Building {args.limit} RQ2 pairs (seed {args.seed})...", flush=True)
    pairs = build_pairs(limit=args.limit, seed=args.seed)
    write_pairs(pairs, args.pairs_output)
    preview = write_preview(pairs, args.preview_output, args.seed)

    counts = {c: sum(1 for p in pairs if p["display_order"]["shown_as_A"] == c)
              for c in (SCAFFOLDED, ANSWER_GIVING)}
    print(f"\nWrote {args.pairs_output}")
    print(f"Wrote {args.preview_output}")
    print(f"Shown as A: {counts[SCAFFOLDED]} scaffolded / "
          f"{counts[ANSWER_GIVING]} answer_giving")
    weak = [p["problem_id"] for p in pairs if p["_hidden"]["weak_stimulus"]]
    if weak:
        print(f"WARNING: {len(weak)} weak stimulus/stimuli (situation model "
              f"abstained): {', '.join(weak)}")
    # Repeated after the "Wrote ..." lines on purpose: those lines are what
    # invite the assumption that the study's materials just changed.
    if frozen_exists:
        print(f"NOTE: {os.path.relpath(FROZEN_PAIRS_PATH, REPO_ROOT)} is "
              "UNCHANGED by this run and remains the canonical stimulus set.")
    if not args.no_print:
        print("\n" + "=" * 70 + "\n")
        print(preview)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
